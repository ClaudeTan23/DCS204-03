package com.assignment2;

/**
 * TreeNode represents a single node in the Binary Search Tree.
 */
public class TreeNode {

    int value;
    TreeNode left;
    TreeNode right;

    /**
     * Constructor
     *
     * @param value Value stored in the node
     */
    public TreeNode(int value) {

        this.value = value;
        this.left = null;
        this.right = null;

    }

}